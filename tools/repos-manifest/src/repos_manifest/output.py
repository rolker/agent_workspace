"""Writing what resolving produces, whole or not at all.

The output directory (``--out``) holds, in the default layout:

- ``<layer>.repos`` for each layer with repos for this machine (``_unnamed.repos`` for the
  unnamed first layer), with ``type``, ``url`` and ``version`` for each repo;
- ``layers.txt``: the layers written, one per line, in order;
- ``optional.txt``: the keys of the selected repos that are optional, one per line, in layer
  order and then manifest order;
- ``.repos-manifest-output``: a marker that says the directory was written by this tool.

Every file starts with ``#`` comment lines that say which manifest, role, distro and extra
groups it came from. A reader of the two lists skips lines that start with ``#``.

The files are written into a new hidden directory beside ``--out`` and moved into place, so
``--out`` is replaced whole or not at all. An existing ``--out`` is replaced only when it is
empty or holds the marker. The hidden directories are named ``.<name>.new-<pid>-<random>`` and
``.<name>.old-<pid>-<random>``; the ones a killed run left beside ``--out`` are removed at the
start of the next run when their process has ended and they hold the marker or are empty; if
``--out`` is missing and the previous output is aside in a marked ``.old`` one, it is moved back
first. An ``--out`` named like them is refused.
"""

from __future__ import annotations

import errno
import os
import re
import shutil
import signal
import stat
import sys
import tempfile
from contextlib import contextmanager
from pathlib import Path
from typing import Callable, Dict, List, Optional

import yaml

from .selection import Resolved
from .yamlload import ManifestError, has_unsafe_char

MARKER = ".repos-manifest-output"
LAYERS_FILE = "layers.txt"
OPTIONAL_FILE = "optional.txt"

_MARKER_TEXT = (
    "# This directory was written by repos-manifest resolve; the next resolve replaces it.\n"
)
_SWAP_SIGNALS = tuple(
    sig for sig in (getattr(signal, name, None) for name in ("SIGINT", "SIGTERM", "SIGHUP")) if sig
)


def head_comment(resolved: Resolved) -> str:
    """The comment at the head of every output file. The manifest is named as it was given."""
    extra = ", ".join(resolved.extra_groups) if resolved.extra_groups else "(none)"
    lines = [
        "# Generated by repos-manifest resolve; resolve again rather than editing.",
        f"# manifest: {resolved.source}",
        f"# role: {resolved.role if resolved.role is not None else '(none)'}",
        f"# distro: {resolved.distro if resolved.distro is not None else '(none)'}",
        f"# extra groups: {extra}",
    ]
    for line in lines:
        if has_unsafe_char(line):
            raise ManifestError(
                "refusing to write the head comment: the manifest's location or a name holds a"
                " control or invisible character"
            )
    return "\n".join(lines) + "\n"


def output_files(resolved: Resolved) -> Dict[str, str]:
    """The name and text of every file of the default layout, built before anything is
    written."""
    head = head_comment(resolved)
    files: Dict[str, str] = {}
    for layer in resolved.layers:
        repositories = {}
        for repo in layer.repos:
            entry = {"type": repo.type, "url": repo.url}
            if repo.version is not None:
                entry["version"] = repo.version
            repositories[repo.key] = entry
        body = yaml.safe_dump(
            {"repositories": repositories},
            default_flow_style=False,
            sort_keys=False,
            width=4096,
        )
        files[f"{layer.name}.repos"] = head + "\n" + body
    files[LAYERS_FILE] = head + "".join(f"{layer.name}\n" for layer in resolved.layers)
    files[OPTIONAL_FILE] = head + "".join(f"{key}\n" for key in resolved.optional)
    return files


def strip_head_comment(text: str) -> str:
    """The text of an output file without its head comment and the blank line after it."""
    lines = text.splitlines(keepends=True)
    index = 0
    while index < len(lines) and lines[index].startswith("#"):
        index += 1
    if index < len(lines) and lines[index].strip() == "" and lines[0].startswith("#"):
        index += 1
    return "".join(lines[index:])


def _is_ours_or_empty(path: Path) -> bool:
    """A directory (not a link) that is empty or holds the marker."""
    if path.is_symlink() or not path.is_dir():
        return False
    return (path / MARKER).is_file() or not any(path.iterdir())


# The name of a temporary directory: `.<name>.new-<pid>-<random>` or `.<name>.old-...`, where
# <pid> is the process that made it and <random> is what mkdtemp adds.
_TEMP_SUFFIX = r"\.(?:new|old)-(?P<pid>[0-9]+)-[a-z0-9_]{8}"
_TEMP_NAME = re.compile(r"\..+" + _TEMP_SUFFIX)


def _temp_prefix(name: str, kind: str) -> str:
    return f".{name}.{kind}-{os.getpid()}-"


def _process_has_ended(pid: int) -> bool:
    """True only when no process `pid` is running (on POSIX; elsewhere it is never known)."""
    if os.name != "posix" or pid <= 0:
        return False
    if pid == os.getpid():
        return True  # an earlier run with the same id; this run has made none yet
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return True
    except OSError:  # PermissionError: it runs, as another user
        return False
    except (OverflowError, ValueError):  # not a process id: not a directory this tool made
        return False
    return False


def _make_writable(path: Path) -> None:
    """Give the owner full access to `path` and every directory below it, so that a read-only
    directory anywhere in the tree does not stop its removal. A link is not followed, and the
    mode of what it points to is left as it is."""
    os.chmod(path, stat.S_IRWXU)

    def fail(exc: OSError) -> None:
        raise exc

    for top, directories, _files in os.walk(path, onerror=fail):
        for directory in directories:
            below = os.path.join(top, directory)
            if stat.S_ISDIR(os.lstat(below).st_mode):
                os.chmod(below, stat.S_IRWXU)


def _remove_ours(path: Path) -> Optional[str]:
    """Remove a directory this tool made, its marker last, so that a removal cut short leaves a
    directory that still holds the marker, which a later run sweeps. It and every directory in
    it are made writable first, so a read-only copy is removed too. Returns why it could not be
    removed, or None; what is left is still marked."""
    try:
        _make_writable(path)
        for entry in list(path.iterdir()):
            if entry.name == MARKER:
                continue
            if entry.is_dir() and not entry.is_symlink():
                shutil.rmtree(entry)
            else:
                entry.unlink()
        (path / MARKER).unlink(missing_ok=True)
        path.rmdir()
    except OSError as exc:
        return exc.strerror or "an OS error"
    return None


def _discard_previous_output(old: Path, parent: Path, name: str) -> Optional[str]:
    """Remove the previous output, aside in `old` after a good swap. It is first renamed to a
    `.new-` name, which a later run sweeps but never puts back, so a removal cut short can never
    come back as the output. Returns why it could not be removed, or None."""
    try:
        doomed = Path(tempfile.mkdtemp(prefix=_temp_prefix(name, "new"), dir=parent))
    except OSError as exc:
        return exc.strerror or "an OS error"
    try:
        os.rename(old, doomed)  # onto the empty directory mkdtemp made
    except OSError as exc:
        _remove_ours(doomed)
        return exc.strerror or "an OS error"
    return _remove_ours(doomed)


def _sweep_leftovers(parent: Path, name: str, out: Path) -> None:
    """Remove the hidden directories a run that was killed left beside this output: named for
    this output, made by a process that has ended, and holding the marker or empty. Nothing
    else is touched, a run still going included. One that cannot be removed is named in a
    warning (`out` as it was given) and left, still marked, for a later run."""
    leftover = re.compile(re.escape(f".{name}") + _TEMP_SUFFIX)
    for entry in parent.iterdir():
        match = leftover.fullmatch(entry.name)
        if match and _process_has_ended(int(match.group("pid"))) and _is_ours_or_empty(entry):
            problem = _remove_ours(entry)
            if problem is not None:
                print(
                    f"WARNING: --out {out}: {entry.name}, left beside it by an earlier run, could"
                    f" not be removed ({problem}); a later resolve to the same place tries again,"
                    " or remove it by hand",
                    file=sys.stderr,
                )


def _put_back_the_previous_output(parent: Path, name: str, out: Path) -> None:
    """A run killed between the two renames leaves no `--out`, and the previous output aside in
    a marked `.<name>.old-<pid>-<random>` directory. Move it back into place before anything
    else, so that it is not lost if this run fails too; the newest, if there are several."""
    if os.path.lexists(out) or not parent.is_dir():
        return
    aside = re.compile(re.escape(f".{name}") + r"\.old-(?P<pid>[0-9]+)-[a-z0-9_]{8}")
    found = []
    for entry in parent.iterdir():
        match = aside.fullmatch(entry.name)
        if (
            match
            and _process_has_ended(int(match.group("pid")))
            and not entry.is_symlink()
            and (entry / MARKER).is_file()
        ):
            found.append((entry.stat().st_mtime, entry))
    if found:
        os.rename(max(found)[1], out)


@contextmanager
def _signals_held():
    """Hold SIGINT, SIGTERM and SIGHUP for the two renames, so a signal cannot stop the run
    between them; a held signal is delivered when the renames are done."""
    if not hasattr(signal, "pthread_sigmask") or not _SWAP_SIGNALS:
        yield
        return
    previous = signal.pthread_sigmask(signal.SIG_BLOCK, _SWAP_SIGNALS)
    try:
        yield
    finally:
        signal.pthread_sigmask(signal.SIG_SETMASK, previous)


def _write_text(path: Path, text: str) -> None:
    with open(path, "x", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def _on_disk(out: Path) -> Path:
    """`out` made absolute, with the directory it is in passed through `os.path.realpath` (links
    resolved, '..' folded) and its last part kept as it is, so that a link there is seen (and
    refused). A last part of '.' or '..' is resolved too."""
    given = os.path.join(os.getcwd(), os.fspath(out)).rstrip(os.sep) or os.sep
    head, tail = os.path.split(given)
    if tail in ("", ".", ".."):
        return Path(os.path.realpath(given))
    return Path(os.path.realpath(head)) / tail


def write_output(
    out: Path, files: Dict[str, str], on_replaced: Optional[Callable[[], None]] = None
) -> List[Path]:
    """Write `files` as the whole content of `out`; returns the paths written, as they are on
    the disk. `on_replaced` is called as soon as the new output is in place, before any held
    signal is delivered."""
    try:
        out_abs = _on_disk(out)
        cwd = Path(os.path.realpath(os.getcwd()))
    except OSError as exc:
        raise ManifestError(
            f"--out {out}: cannot be checked ({exc.strerror or 'an OS error'})"
        ) from None
    if out_abs.parent == out_abs:
        raise ManifestError(f"--out {out}: cannot be the root directory")
    if out_abs == cwd or out_abs in cwd.parents:
        raise ManifestError(
            f"--out {out}: is the current directory or one of its parents, which replacing it"
            " would delete from under this shell; give a directory beside or below it"
        )
    parent, name = out_abs.parent, out_abs.name
    if _TEMP_NAME.fullmatch(name):
        raise ManifestError(
            f"--out {out}: is named like the tool's temporary directories, which a later run"
            " may remove; give it another name"
        )
    try:
        _put_back_the_previous_output(parent, name, out_abs)
        if out_abs.is_symlink():
            raise ManifestError(f"--out {out}: is a symbolic link; give the directory itself")
        exists = out_abs.exists()
        if exists and not out_abs.is_dir():
            raise ManifestError(f"--out {out}: exists and is not a directory")
        if exists and not _is_ours_or_empty(out_abs):
            raise ManifestError(
                f"--out {out}: exists, is not empty and was not written by repos-manifest; it is"
                " left as it is"
            )
    except OSError as exc:
        raise ManifestError(
            f"--out {out}: cannot be checked ({exc.strerror or 'an OS error'})"
        ) from None
    try:
        try:
            parent.mkdir(parents=True, exist_ok=True)
        except FileExistsError:  # a part of the path is a file
            raise NotADirectoryError(errno.ENOTDIR, os.strerror(errno.ENOTDIR)) from None
        _sweep_leftovers(parent, name, out)
        new = Path(tempfile.mkdtemp(prefix=_temp_prefix(name, "new"), dir=parent))
    except OSError as exc:
        raise ManifestError(
            f"--out {out}: cannot be written ({exc.strerror or 'an OS error'})"
        ) from None
    old = None
    try:
        # mkdtemp makes a private directory. The output keeps the mode of the one it replaces,
        # or gets the mode a plain mkdir would.
        if exists:
            mode = stat.S_IMODE(os.stat(out_abs).st_mode)
        else:
            umask = os.umask(0)
            os.umask(umask)
            mode = 0o777 & ~umask
        _write_text(new / MARKER, _MARKER_TEXT)
        for file_name, text in files.items():
            _write_text(new / file_name, text)
        # After the files are written, so that a read-only mode does not stop the writing.
        os.chmod(new, mode)
        if exists:
            old = Path(tempfile.mkdtemp(prefix=_temp_prefix(name, "old"), dir=parent))
        with _signals_held():
            if old is not None:
                os.rename(out_abs, old)  # onto the empty directory mkdtemp made
            os.rename(new, out_abs)
            if on_replaced is not None:
                on_replaced()
    except OSError as exc:
        raise ManifestError(
            f"--out {out}: cannot be written ({exc.strerror or 'an OS error'})"
        ) from None
    finally:
        # Whatever stopped the run (an OS error, or an interrupt where signals cannot be held),
        # the output is the previous one or the new one, never neither. What is on the disk
        # says how far the swap got: no `--out` means the previous output is aside, in `old`.
        if old is not None and not os.path.lexists(out_abs):
            try:
                os.rename(old, out_abs)
            except OSError:
                # It stays where it is, marked, and is not removed by this run.
                print(
                    f"WARNING: --out {out}: is now missing; the previous output is in {old}, and"
                    " the next resolve to the same place puts it back",
                    file=sys.stderr,
                )
                old = None
        if new.exists():
            _remove_ours(new)
        if old is not None and old.exists():
            problem = _discard_previous_output(old, parent, name)
            if problem is not None:
                print(
                    f"WARNING: --out {out}: the previous output, moved aside beside it, could"
                    f" not be removed ({problem}); a later resolve to the same place tries again",
                    file=sys.stderr,
                )
    return [out_abs / file_name for file_name in files]
