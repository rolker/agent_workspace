def test_sigterm_while_resolving_ends_the_run_and_leaves_nothing_behind(
    manifest, tmp_path, monkeypatch, capsys
):
    # The test's own handler stands for whatever the caller had: the tool's handler raises,
    # the temporary directory is removed, and the signal is then delivered to the caller's.
    received = []
    previous = signal.signal(signal.SIGTERM, lambda signum, _frame: received.append(signum))
    real_write_text = output._write_text

    def write_text(path, text):
        real_write_text(path, text)
        if path.name == "core.repos":
            os.kill(os.getpid(), signal.SIGTERM)

    monkeypatch.setattr(output, "_write_text", write_text)
    try:
        rc = _resolve(manifest, tmp_path / "out", "--role", "robot", "--distro", "jazzy")
    finally:
        signal.signal(signal.SIGTERM, previous)
    assert rc == 128 + signal.SIGTERM
    assert received == [signal.SIGTERM]
    assert capsys.readouterr().err == "ERROR: stopped by SIGTERM; nothing was written\n"
    assert _names(tmp_path) == ["m.manifest.yaml"]


def _swap_with(monkeypatch, during_first_rename):
    """Run `during_first_rename` just after the first rename of the swap (the previous output
    moved aside, the new one not yet in place)."""
    real_rename = os.rename

    def rename(src, dst):
        real_rename(src, dst)
        if ".old-" in str(dst):
            during_first_rename()

    monkeypatch.setattr(output.os, "rename", rename)


def test_sigint_is_held_during_the_swap(manifest, tmp_path, monkeypatch):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "--role", "dev", "--distro", "jazzy") == 0
    held = []
    _swap_with(monkeypatch, lambda: held.append(signal.pthread_sigmask(signal.SIG_BLOCK, [])))
    assert _resolve(manifest, out, "--role", "robot", "--distro", "jazzy") == 0
    assert held and {signal.SIGINT, signal.SIGTERM, signal.SIGHUP} <= held[0]


def test_ctrl_c_during_the_swap_leaves_the_new_output_and_says_so(
    manifest, tmp_path, monkeypatch, capsys
):
    # Held during the swap, SIGINT is reported as SIGTERM is: no KeyboardInterrupt, no traceback.
    assert signal.getsignal(signal.SIGINT) is signal.default_int_handler
    out = tmp_path / "out"
    assert _resolve(manifest, out, "--role", "dev", "--distro", "jazzy") == 0
    capsys.readouterr()
    _swap_with(monkeypatch, lambda: os.kill(os.getpid(), signal.SIGINT))
    assert _resolve(manifest, out, "--role", "robot", "--distro", "jazzy") == 128 + signal.SIGINT
    assert capsys.readouterr().err == (
        f"ERROR: stopped by SIGINT after --out {out} was replaced by the new output\n"
    )
    assert "# role: robot\n" in (out / "layers.txt").read_text()
    assert _names(tmp_path) == ["m.manifest.yaml", "out"]
    assert signal.getsignal(signal.SIGINT) is signal.default_int_handler


