"""What `resolve` and `validate` say about the manifests read through `base`: the head
comment of the output and the lines `validate` prints."""

import os
import textwrap

from repos_manifest.cli import main

REPO = "    type: git\n    url: https://example.org/{name}.git\n"


def _write(directory, name, text):
    path = directory / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text))
    return path


def _repos(*names):
    return "repositories:\n" + "".join(f"  {n}:\n" + REPO.format(name=n) for n in names)


def _real(path):
    return os.path.realpath(path)


def _diamond(tmp_path):
    c = _write(tmp_path, "c.yaml", _repos("c"))
    a = _write(tmp_path, "a.yaml", "base: c.yaml\n" + _repos("a"))
    b = _write(tmp_path, "b.yaml", "base: c.yaml\n" + _repos("b"))
    leaf = _write(tmp_path, "m.yaml", "base: [a.yaml, b.yaml]\n" + _repos("m"))
    return c, a, b, leaf


# --- What resolve and validate say -----------------------------------------------------------


def test_the_head_comment_names_each_parent_in_reading_order(tmp_path, monkeypatch):
    c, a, b, _ = _diamond(tmp_path)
    monkeypatch.chdir(tmp_path)
    out = tmp_path / "out"
    assert main(["resolve", "--manifest", "m.yaml", "--out", str(out)]) == 0
    head = (
        "# Generated by repos-manifest resolve; resolve again rather than editing.\n"
        "# manifest: m.yaml\n"
        f"# base: {_real(c)}\n"
        f"# base: {_real(a)}\n"
        f"# base: {_real(b)}\n"
        "# role: (none)\n"
        "# distro: (none)\n"
        "# extra groups: (none)\n"
    )
    for name in ("layers.txt", "optional.txt", "_unnamed.repos"):
        assert (out / name).read_text().startswith(head)


def test_validate_names_each_parent(tmp_path, capsys):
    c, a, b, leaf = _diamond(tmp_path)
    assert main(["validate", "--manifest", str(leaf)]) == 0
    assert capsys.readouterr().out == (
        f"base: {_real(c)}\nbase: {_real(a)}\nbase: {_real(b)}\n"
        "role (none), distro (none): 4 repos in 1 layers\n"
        f"{leaf}: valid\n"
    )
