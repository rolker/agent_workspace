"""`resolve --layout`: the default `flat` output is unchanged; `manifest-dir` writes the directory
shape the ros2_colcon adapter reads (repos/<layer>.repos, layers.txt, optional_layers.txt)."""

from pathlib import Path

import pytest
import yaml

from ros_manifest.cli import main

# Five layers:
# - underlay, core: always selected.
# - sim: optional; its only repo is absent for 'humble', so it is empty there.
# - site: optional; selected for every distro.
# - gui: required; its only repo is in a default-exclude group, so empty for role 'dev'.
MANIFEST = """
layers: [underlay, core, sim, site, gui]
optional_layers: [sim, site]
repos:
  underlay:
    base_lib:
      url: https://example.com/base_lib.git
      ref: main
  core:
    core_pkg:
      url: https://example.com/core_pkg.git
      ref: '2.0'
  sim:
    sim_pkg:
      url: https://example.com/sim_pkg.git
      ref: main
      distros:
        humble: {absent: true}
  site:
    site_cfg:
      url: https://example.com/site_cfg.git
      ref: main
  gui:
    viewer:
      url: https://example.com/viewer.git
      ref: main
groups:
  gui:
    default: exclude
    repos: [viewer]
roles:
  dev: {}
  operator:
    add: [gui]
"""


@pytest.fixture
def manifest(tmp_path) -> Path:
    path = tmp_path / "manifest.yaml"
    path.write_text(MANIFEST)
    return path


def _resolve(manifest: Path, out: Path, role: str, distro: str, *layout: str) -> int:
    return main(
        [
            "resolve",
            "--manifest",
            str(manifest),
            "--role",
            role,
            "--distro",
            distro,
            "--out",
            str(out),
            *layout,
        ]
    )


def _files(root: Path) -> set:
    return {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}


def _entries(path: Path) -> list:
    """The non-comment lines of a layers.txt-style file."""
    return [line for line in path.read_text().splitlines() if not line.startswith("#")]


def test_manifest_dir_file_set(manifest, tmp_path):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "jazzy", "--layout", "manifest-dir") == 0
    assert _files(out) == {
        "layers.txt",
        "optional_layers.txt",
        "repos/underlay.repos",
        "repos/core.repos",
        "repos/sim.repos",
        "repos/site.repos",
    }


def test_layers_txt_order_and_empty_layer_omitted(manifest, tmp_path):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "jazzy", "--layout", "manifest-dir") == 0
    # 'gui' selects nothing for role dev: in neither file, no .repos written.
    assert _entries(out / "layers.txt") == ["underlay", "core", "sim", "site"]
    assert _entries(out / "optional_layers.txt") == ["sim", "site"]

    out_op = tmp_path / "out_operator"
    assert _resolve(manifest, out_op, "operator", "jazzy", "--layout", "manifest-dir") == 0
    assert _entries(out_op / "layers.txt") == ["underlay", "core", "sim", "site", "gui"]
    assert (out_op / "repos" / "gui.repos").is_file()


def test_optional_layer_empty_for_a_distro_is_in_neither_file(manifest, tmp_path):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "humble", "--layout", "manifest-dir") == 0
    assert _entries(out / "layers.txt") == ["underlay", "core", "site"]
    assert _entries(out / "optional_layers.txt") == ["site"]
    assert not (out / "repos" / "sim.repos").exists()


def test_optional_layers_txt_written_when_none_are_optional(tmp_path):
    path = tmp_path / "manifest.yaml"
    path.write_text(
        "layers: [core]\n"
        "repos:\n"
        "  core:\n"
        "    a: {url: 'https://example.com/a.git', ref: main}\n"
        "roles:\n"
        "  dev: {}\n"
    )
    out = tmp_path / "out"
    assert _resolve(path, out, "dev", "jazzy", "--layout", "manifest-dir") == 0
    assert (out / "optional_layers.txt").is_file()
    assert _entries(out / "optional_layers.txt") == []


def test_text_files_start_with_provenance_line(manifest, tmp_path):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "jazzy", "--layout", "manifest-dir") == 0
    for name in ("layers.txt", "optional_layers.txt"):
        first = (out / name).read_text().splitlines()[0]
        assert first.startswith("# Generated by ros-manifest — role=dev distro=jazzy")
        assert str(manifest) in first


def test_manifest_dir_repos_match_flat_repos(manifest, tmp_path):
    flat = tmp_path / "flat"
    mdir = tmp_path / "mdir"
    assert _resolve(manifest, flat, "dev", "jazzy") == 0
    assert _resolve(manifest, mdir, "dev", "jazzy", "--layout", "manifest-dir") == 0
    for layer in ("underlay", "core", "sim", "site"):
        assert (mdir / "repos" / f"{layer}.repos").read_text() == (
            flat / f"{layer}.repos"
        ).read_text()


@pytest.mark.parametrize("layout", [(), ("--layout", "flat")])
def test_flat_layout_writes_none_of_the_new_files(manifest, tmp_path, layout):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "jazzy", *layout) == 0
    assert _files(out) == {"underlay.repos", "core.repos", "sim.repos", "site.repos"}


def test_numeric_looking_ref_is_written_quoted(manifest, tmp_path):
    # The manifest quotes the ref ('2.0'); PyYAML writes it back quoted so a YAML reader gets
    # the string "2.0", not a float. A shell reader of `version:` sees the quotes.
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "jazzy", "--layout", "manifest-dir") == 0
    text = (out / "repos" / "core.repos").read_text()
    assert "    version: '2.0'\n" in text
    assert yaml.safe_load(text)["repositories"]["core_pkg"]["version"] == "2.0"


def test_zero_repos_manifest_dir_warns_exits_zero_and_lists_nothing(tmp_path, capsys):
    path = tmp_path / "manifest.yaml"
    path.write_text(
        "layers: [core]\n"
        "repos:\n"
        "  core:\n"
        "    a:\n"
        "      url: https://example.com/a.git\n"
        "      ref: main\n"
        "      distros:\n"
        "        humble: {absent: true}\n"
        "roles:\n"
        "  dev: {}\n"
    )
    out = tmp_path / "out"
    assert _resolve(path, out, "dev", "humble", "--layout", "manifest-dir") == 0
    assert "selected zero repos" in capsys.readouterr().err
    assert _entries(out / "layers.txt") == []
    assert _entries(out / "optional_layers.txt") == []
    assert _files(out) == {"layers.txt", "optional_layers.txt"}


def test_cli_prints_the_text_files_it_wrote(manifest, tmp_path, capsys):
    out = tmp_path / "out"
    assert _resolve(manifest, out, "dev", "jazzy", "--layout", "manifest-dir") == 0
    stdout = capsys.readouterr().out
    assert f"wrote {out / 'repos' / 'core.repos'} (core)" in stdout
    assert f"wrote {out / 'layers.txt'}" in stdout
    assert f"wrote {out / 'optional_layers.txt'}" in stdout


def test_unknown_layout_is_a_usage_error(manifest, tmp_path, capsys):
    with pytest.raises(SystemExit) as excinfo:
        _resolve(manifest, tmp_path / "out", "dev", "jazzy", "--layout", "west")
    assert excinfo.value.code == 2
    assert "invalid choice" in capsys.readouterr().err
