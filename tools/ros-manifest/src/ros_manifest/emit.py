"""Emit vcstool/vcs2l-compatible `.repos` files, one per layer, with a provenance header.

Two output layouts (``LAYOUTS``):

- ``flat`` (default): ``<out>/<layer>.repos`` and nothing else.
- ``manifest-dir``: ``<out>/repos/<layer>.repos``, ``<out>/layers.txt`` (the layers written, in
  order, one per line) and ``<out>/optional_layers.txt`` (the written layers the manifest marks
  optional; always written, possibly empty). Each text file starts with a ``#`` provenance line.
  This is the directory shape the ros2_colcon adapter reads.

In both layouts a layer with zero selected repos for the role and distro is not written, and in
``manifest-dir`` it is in neither text file.

``schema.py`` refuses unsafe names and values when a manifest is parsed. As a second line, this
module refuses to write a header or list line that holds a control character, and refuses any
path that does not resolve inside the output directory; every file's text is built and checked
before the first one is written.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional, Set

import yaml

from .merge import MergedManifest
from .schema import ManifestError, has_control_char
from .selectors import resolve_distro_ref

HEADER_PREFIX = "#"
LAYOUT_FLAT = "flat"
LAYOUT_MANIFEST_DIR = "manifest-dir"
LAYOUTS = (LAYOUT_FLAT, LAYOUT_MANIFEST_DIR)


def _line(text: str, what: str) -> str:
    """One line of a generated file, refused if it could split into more than one."""
    if has_control_char(text):
        raise ManifestError(
            f"refusing to write {what}: a value in it contains a control character (newline,"
            " carriage return or similar)"
        )
    return text


def _repos_body(merged: MergedManifest, layer: str, repo_names_in_order, distro: str) -> str:
    repositories = {}
    for repo_name in repo_names_in_order:
        ref = resolve_distro_ref(merged, repo_name, distro)
        if ref is None:
            continue
        entry = merged.repos[repo_name].entry
        repositories[repo_name] = {"type": entry.type, "url": entry.url, "version": ref}
    if not repositories:
        return ""
    return yaml.dump({"repositories": repositories}, default_flow_style=False, sort_keys=False)


def _header(merged: MergedManifest, layer: str, role: str, distro: str, repo_names) -> str:
    lines = [
        f"{HEADER_PREFIX} Generated by ros-manifest — layer={layer} role={role} distro={distro}",
        f"{HEADER_PREFIX} Provenance (repo: defining manifest):",
    ]
    for repo_name in repo_names:
        lines.append(f"{HEADER_PREFIX}   {repo_name}: {merged.repos[repo_name].source}")
    what = f"the header of the {layer!r} .repos file"
    return "\n".join(_line(line, what) for line in lines) + "\n\n"


def emit_layer(
    merged: MergedManifest, layer: str, selected: Set[str], role: str, distro: str
) -> Optional[str]:
    """Return the full `.repos` file text for `layer`, or None if it would be empty."""
    repo_names_in_order = [name for name in merged.layer_repos[layer] if name in selected]
    repo_names_in_order = [
        name for name in repo_names_in_order if resolve_distro_ref(merged, name, distro) is not None
    ]
    if not repo_names_in_order:
        return None
    body = _repos_body(merged, layer, repo_names_in_order, distro)
    header = _header(merged, layer, role, distro, repo_names_in_order)
    return header + body


def _list_file_text(
    merged: MergedManifest, role: str, distro: str, layers: List[str], name: str
) -> str:
    header = (
        f"{HEADER_PREFIX} Generated by ros-manifest — role={role} distro={distro}"
        f" manifests (base first): {', '.join(merged.sources)}"
    )
    lines = [header] + list(layers)
    return "".join(_line(line, name) + "\n" for line in lines)


def _inside(out_root: Path, path: Path) -> Path:
    """Refuse a path that does not resolve inside the output directory (`--out`)."""
    if not path.resolve().is_relative_to(out_root):
        raise ManifestError(f"refusing to write {str(path)!r}: it is outside the output directory")
    return path


def emit_manifest(
    merged: MergedManifest,
    selected: Set[str],
    role: str,
    distro: str,
    out_dir: Path,
    layout: str = LAYOUT_FLAT,
) -> Dict[str, Path]:
    """Write one `.repos` file per non-empty layer under `out_dir` in the given layout (see the
    module docstring). Returns layer -> `.repos` path."""
    if layout not in LAYOUTS:
        raise ValueError(f"unknown layout {layout!r} (known: {', '.join(LAYOUTS)})")
    out_dir = Path(out_dir)
    out_root = out_dir.resolve()
    repos_dir = out_dir / "repos" if layout == LAYOUT_MANIFEST_DIR else out_dir

    # Build and check everything first, so a refusal leaves no partial output.
    files: List[tuple] = []  # (path, text)
    written: Dict[str, Path] = {}
    for layer in merged.layers:
        text = emit_layer(merged, layer, selected, role, distro)
        if text is None:
            continue
        path = _inside(out_root, repos_dir / f"{layer}.repos")
        files.append((path, text))
        written[layer] = path
    if layout == LAYOUT_MANIFEST_DIR:
        layers = list(written)
        optional = [layer for layer in layers if layer in merged.optional_layers]
        for name, listed in (("layers.txt", layers), ("optional_layers.txt", optional)):
            text = _list_file_text(merged, role, distro, listed, name)
            files.append((_inside(out_root, out_dir / name), text))

    repos_dir.mkdir(parents=True, exist_ok=True)
    for path, text in files:
        path.write_text(text)
    return written


def strip_provenance_header(text: str) -> str:
    """Remove the leading `#`-prefixed header block and the blank line after it. Used by tests
    that assert byte-equivalence with hand-authored `.repos` fixtures "modulo the provenance
    header"."""
    lines = text.splitlines(keepends=True)
    idx = 0
    while idx < len(lines) and lines[idx].startswith(HEADER_PREFIX):
        idx += 1
    if idx < len(lines) and lines[idx].strip() == "":
        idx += 1
    return "".join(lines[idx:])
